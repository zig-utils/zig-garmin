import { $ } from 'bun'
await $`zig build test`
await $`zig build wasm`
const bytes = new Uint8Array(await Bun.file('zig-out/bin/garmin.wasm').arrayBuffer())
await Bun.write('bindings/wasm-bytes.ts', `// Generated by scripts/build.ts from src/wasm.zig.\nexport const wasmBytes: number[] = ${JSON.stringify([...bytes])}\n`)
const result = await Bun.build({ entrypoints: ['bindings/index.ts'], outdir: 'dist', target: 'browser', format: 'esm', minify: true })
if (!result.success) throw new Error(result.logs.map(log => log.message).join('; '))
